verifyNotEmpty(testCase, strfind(txt, ...
    'free_intercept_meV'));
verifyNotEmpty(testCase, strfind(txt, ...
    'zero_slope_meV_sqrtA'));
verifyNotEmpty(testCase, strfind(txt, ...
    'local_fit_sqrt_free_intercept'));
verifyNotEmpty(testCase, strfind(txt, ...
    'local_fit_sqrt_zero_intercept'));
verifyNotEmpty(testCase, strfind(txt, ...
    'powerlaw_deviation_summary.csv'));
verifyNotEmpty(testCase, strfind(txt, ...
    'powerlaw_deviation_sqrt_comparison.png'));
verifyNotEmpty(testCase, strfind(txt, ...
    'powerlaw_deviation_residuals.png'));
end
