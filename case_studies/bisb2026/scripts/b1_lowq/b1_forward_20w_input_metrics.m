function T = b1_forward_20w_input_metrics(p)
%B1_FORWARD_20W_INPUT_METRICS  Summarize the two acquisitions on common windows.
S = load(p.stage1_file,'C');
C = S.C;
B = load(fullfile(p.input_dir,'p2a_cube.mat'),'cube');
B = B.cube;
F = readtable(fullfile(p.input_dir,'frame_descriptors_p2a.csv'));
W = readtable(fullfile(p.input_dir,'w_kernel_x.csv'));
w = W(W.w_meV==8 & W.block==0,:);
R = readtable(fullfile(p.response_dir,'response_slices.csv'));
J = readtable(fullfile(p.response_dir,'response_joint_fit.csv'));
j = J(strcmp(J.data,'capture-corrected slice weights'),:);
N = readtable(fullfile(p.diag_dir,'noise_coefficients.csv'));
X = readtable(fullfile(p.input_dir,'bending_vs_beam_position.csv'));
f = F.mu_gauss_w8;
s6 = B.b6.pos_narrow_mode;
s12 = B.b12.pos_narrow_mode;
central = R.n_blocks==6 & abs(R.q)<1e-9;
within = R.n_blocks==6 & abs(R.q)<=0.005+1e-9;
n = N.E_meV>=392;
blockDiff = s6-mean(reshape(s12,2,[]),1);
span = @(x) max(x)-min(x);
lag = corrcoef(f(1:end-1),f(2:end));
T = table(string(p.session),C.dq,C.sigma_probe,std(f),span(f), ...
    std(diff(f)),lag(1,2),span(s6),span(s12),sqrt(mean(blockDiff.^2)), ...
    w.narrow_fwhm_Ainv,w.broad_fraction_total,w.broad_2m, ...
    std(F.common_ref)/mean(F.common_ref),span(B.c_q(abs(B.q)<=0.001+1e-9)), ...
    max(abs(X.measured_slope_on_dq_meV_per_channel)), ...
    median(R.fwhm_meV(central)),median(R.fwhm_meV(within)), ...
    median(R.mass_beyond_40meV(within)),median(R.extra_mass_60_to_100meV(within)), ...
    median(R.chi2dof_window(within)),nnz(R.at_bound(within)),nnz(within), ...
    j.narrow_fwhm_Ainv(1),j.broad_fraction(1),median(j.logrms), ...
    median(N.g_common_beam(n)),median(N.g_first_diff(n)), ...
    'VariableNames',{'session','dq','sigma_legacy','frame_std','frame_range','frame_diff_std', ...
    'frame_lag1','block6_range','block12_range','block_pair_rms','core_narrow_fwhm', ...
    'core_broad_fraction','broad_power','beam_cv','ZLP_center_range_abs_q_le_0p001', ...
    'max_abs_ZLP_beam_slope','ZLP_central_FWHM','ZLP_median_FWHM','ZLP_mass_beyond_40', ...
    'ZLP_mass_60_to_100','slice_median_chi2dof','slice_n_bound','slice_n_total', ...
    'area_narrow_fwhm','area_broad_fraction','area_logrms','common_noise_g_B1','diff_noise_g_B1'});
end
