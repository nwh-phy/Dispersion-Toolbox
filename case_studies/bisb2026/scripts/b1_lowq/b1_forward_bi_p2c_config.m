function P = b1_forward_bi_p2c_config(id, run)
%B1_FORWARD_BI_P2C_CONFIG  Archived geometry and matched P2c window controls.
ids = {'Bi1107_10w','Bi1107_20w','Bi1117_10w','Bi1117_20w'};
j = find(strcmp(ids,id));
assert(isscalar(j),'Unknown Bi acquisition %s.',id);
[c,o,h] = b1_forward_bi_p2b_config(id);
p = c.paths;
keys = {'f698c898','b1b32fd6','dd998d8d','368cf388'};
lo = [200 200 150 250];
ctrl = [180 180 180 300];
P = struct('version','P2c-Bi-2026-11-19','id',id,'run',run,'c',c,'o',o, ...
    'hScan',h,'main',keys{j},'seed',keys{j},'window',[lo(j) 1800], ...
    'control',[ctrl(j) 1800],'nsy',109-52*endsWith(id,'20w'), ...
    'qmax',max(abs(c.exit_q)),'phonon',true,'held',[6 1], ...
    'tail','mirror','gain','none','bands',[250 500;500 1000;1000 1800], ...
    'thresholdGrid',[0 100 150 180 200 225 250 275 300 325 350 400 500 650 800], ...
    'maxIter',85, ...
    'gainBands',[70 180;85 240;100 320],'fastNoise',false,'empirical',false, ...
    'qfloor',0,'gapless',false,'fullB1',false);
if j == 2
    P.seed = '68d16aec';
    P.qmax = 12*bisb_datasets(id).dq;
end
P.archive = p.p2b_dir;
end
