function C = b1_forward_prepare(cfg)
%B1_FORWARD_PREPARE  Make native-channel stage1 and common-beam P1b inputs.
t=tic;
paths=b1_forward_paths(cfg); d=bisb_datasets(paths.session);
root=bisb_find_project_root(fileparts(mfilename('fullpath')));
addpath(genpath(fullfile(root,'src')));
assert(~isfile(paths.stage1_file) && ~isfolder(paths.diag_dir), ...
    'b1_forward_prepare:OutputExists','Stage1 or P1b output already exists for %s.',d.id);
assert(strcmp(b1_sha256({'file',d.path}),d.sha256), ...
    'b1_forward_prepare:Source','Raw file of %s differs from the registry hash.',d.id);
[A, raw]=qe_align_sequence_frames(d.path,d.zero,d.dq,q_select=cfg.qmax, ...
    reference_q=cfg.reference_abs_q,alignment_window=cfg.zlp_window, ...
    energy_zero="detector_peak",raw_profile_window=cfg.raw_profile_window);
T=size(A.F,2);
assert(T==cfg.n_blocks*cfg.frames_per_block,'Unexpected raw frame count.');
zero=A.selected==d.zero; assert(nnz(zero)==1,'Invalid q=0 detector column.');
channels=~zero;
frames=single(A.F(:,:,channels));
center_frames=single(A.F(:,:,zero));
detector_counts=raw.counts_by_energy_frame;
[~,i0]=max(raw.elastic_profile); kk=-2:2;
w=raw.elastic_profile(i0+kk); w=w/sum(w);
sigma=sqrt(max(sum(w.*(kk-sum(w.*kk)).^2)-1/12,0))*d.dq;
C=struct('session',d.id,'E',A.E(:),'q',A.Q(channels),'source_channel',A.selected(channels), ...
    'dq',d.dq,'offsets',A.alignment.measured_offset_pixels,'support',A.alignment.support, ...
    'sigma_probe',sigma,'elastic_q_profile',raw.elastic_profile,'q_axis',raw.q_axis, ...
    'T',T,'raw_path',d.path,'qmax',cfg.qmax,'raw_sha256',d.sha256,'h',d.h,'zero',d.zero, ...
    'native_prepared',true,'valid_channels',raw.valid_channels, ...
    'block',repelem(1:cfg.n_blocks,cfg.frames_per_block), ...
    'raw_peak_pixel',raw.peak_pixel,'reference_pixel',A.alignment.reference_pixel, ...
    'energy_origin_meV',A.energy_origin_meV,'dE',raw.energy_step_meV, ...
    'config_sha256',b1_sha256(cfg));
clear A raw
folder=fileparts(paths.stage1_file); if ~isfolder(folder), mkdir(folder); end
save(paths.stage1_file,'C','frames','center_frames','detector_counts','cfg','-v7.3');
clear frames center_frames detector_counts
b1_p1b_diag([],[],cfg);
fprintf('%s stage1 + P1b in %.2f s | config %s | invalid channels %s\n', ...
    d.id,toc(t),C.config_sha256,mat2str(setdiff(1:numel(C.q_axis),C.valid_channels)));
end
