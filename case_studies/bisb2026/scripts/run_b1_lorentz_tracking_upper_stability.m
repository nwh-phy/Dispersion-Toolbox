function local_write_manual_anchor_template(project_root, summary_dir, best_output)
sessions = {'590', 'n0', '20w'};
anchor = table('Size', [0 7], ...
    'VariableTypes', {'cell', 'double', 'cell', 'double', 'double', ...
    'cell', 'cell'}, ...
    'VariableNames', {'session_request', 'q_Ainv', 'branch_label', ...
    'manual_lower_meV', 'manual_upper_meV', 'reason', 'detail'});
for si = 1:numel(sessions)
    session_dir = local_session_dir(project_root, sessions{si}, ...
        best_output.final_tag);
    failures = local_read_table_if_exists(fullfile(session_dir, ...
        'b1_double_peak_fit_failures.csv'));
    if all(ismember({'q_Ainv', 'status', 'detail'}, ...
            failures.Properties.VariableNames))
        for i = 1:height(failures)
            anchor = [anchor; table(sessions(si), failures.q_Ainv(i), ...
                {'both'}, NaN, NaN, failures.status(i), failures.detail(i), ...
                'VariableNames', anchor.Properties.VariableNames)]; %#ok<AGROW>
        end
    end
    upper = local_read_table_if_exists(fullfile(session_dir, ...
        'b1_double_peak_upper_points.csv'));
    diag_rows = local_upper_diagnostics(local_make_variant(best_output.id, ...
        best_output.final_tag, best_output.final_tag, ...
        'windowed_branch_tracking', false, false, ...
        [best_output.b1_energy_min_meV best_output.b1_energy_max_meV], ...
        best_output.candidate_for_recommendation), ...
        local_session_key_from_dir(session_dir), upper);
    if ~isempty(diag_rows)
        issue = diag_rows.is_upper_medium_jump | ...
            diag_rows.is_upper_large_jump_180 | ...
            diag_rows.is_overbroad_upper_peak;
        for i = find(issue(:).')
            reason = 'upper_tracking_issue';
            if diag_rows.is_overbroad_upper_peak(i)
                reason = 'overbroad_upper_peak';
            elseif diag_rows.is_upper_large_jump_180(i)
                reason = 'upper_large_jump_180';
            elseif diag_rows.is_upper_medium_jump(i)
                reason = 'upper_medium_jump';
            end
            anchor = [anchor; table(sessions(si), diag_rows.q_Ainv(i), ...
                {'upper'}, NaN, NaN, {reason}, {''}, ...
                'VariableNames', anchor.Properties.VariableNames)]; %#ok<AGROW>
        end
    end
end
writetable(anchor, fullfile(summary_dir, ...
    'b1_double_peak_upper_manual_anchor_template.csv'));
end


