function out = run_b1_lorentz_tracking_upper_stability(options)
%RUN_B1_LORENTZ_TRACKING_UPPER_STABILITY Stabilize B1 upper branch.
%
% This controller keeps the existing mandatory Lorentz double-peak,
% signed-q, no +q/-q averaging workflow. It adds upper-branch diagnostics,
% a narrower upper tracking window, and an optional overbroad-upper retry.

arguments
    options.targetScore (1,1) double = 300
    options.runExtraction (1,1) logical = true
    options.runOverlay (1,1) logical = true
    options.runSandboxFit (1,1) logical = true
    options.visualGateApproved (1,1) logical = false
end

script_dir = fileparts(mfilename('fullpath'));
project_root = bisb_find_project_root(script_dir);
addpath(script_dir);
startup_path = fullfile(project_root, 'startup.m');
if isfile(startup_path)
    run(startup_path);
end

summary_dir = fullfile(project_root, 'paper_results', ...
    'b1_lorentz_tracking_optimization_260510_upper_stability');
if ~isfolder(summary_dir)
    mkdir(summary_dir);
end

variants = local_variant_specs();
all_metrics = local_empty_metrics_table();
all_upper_diagnostics = table();
variant_outputs = local_empty_variant_output();

for vi = 1:numel(variants)
    variant = variants(vi);
    fprintf('\n=== B1 upper stability %s ===\n', variant.id);
    if options.runExtraction && variant.run_extraction
        local_run_variant(project_root, summary_dir, variant);
    end
    [metrics, upper_diag] = local_finalize_variant(project_root, ...
        summary_dir, variant);
    all_metrics = [all_metrics; metrics]; %#ok<AGROW>
    all_upper_diagnostics = [all_upper_diagnostics; upper_diag]; %#ok<AGROW>
    score = local_variant_score(metrics, variant.id);
    gate = local_gate_status(metrics, variant.id, options.targetScore);
    overlay = struct('png', "", 'pdf', "");
    if options.runOverlay
        overlay = run_b1_double_peak_waterfall_extraction_overlay( ...
            dateTag=variant.final_tag);
    end
    variant_outputs(end + 1) = local_variant_output(variant, score, ...
        gate, overlay); %#ok<AGROW>
end

metrics_path = fullfile(summary_dir, ...
    'b1_lorentz_tracking_upper_stability_metrics.csv');
writetable(all_metrics, metrics_path);
diagnostics_path = fullfile(summary_dir, ...
    'b1_lorentz_tracking_upper_stability_upper_jump_gamma_R2.csv');
writetable(all_upper_diagnostics, diagnostics_path);
variant_path = fullfile(summary_dir, ...
    'b1_lorentz_tracking_upper_stability_variants.csv');
writetable(local_variant_outputs_table(variant_outputs), variant_path);

best_output = local_choose_best_output(variant_outputs);
local_copy_variant_overlays(summary_dir, variant_outputs);
gate_passed = best_output.metric_gate_passed;
if strlength(best_output.overlay_png) > 0 && isfile(best_output.overlay_png)
    copyfile(best_output.overlay_png, fullfile(summary_dir, ...
        'b1_double_peak_lorentz_tracking_upper_stability_overlay_three_dataset_comparison.png'));
end
if strlength(best_output.overlay_pdf) > 0 && isfile(best_output.overlay_pdf)
    copyfile(best_output.overlay_pdf, fullfile(summary_dir, ...
        'b1_double_peak_lorentz_tracking_upper_stability_overlay_three_dataset_comparison.pdf'));
end

fit_outputs = struct();
if gate_passed && options.visualGateApproved && options.runSandboxFit
    local_write_candidate_marker(summary_dir, best_output, options.targetScore);
    fit_outputs = local_run_final_candidate_fit(project_root, ...
        best_output.final_tag);
elseif gate_passed
    local_write_visual_review_marker(summary_dir, best_output, ...
        options.targetScore);
else
    local_write_manual_anchor_template(project_root, summary_dir, best_output);
end

readme_path = fullfile(summary_dir, ...
    'README_lorentz_tracking_upper_stability.md');
local_write_readme(readme_path, all_metrics, variant_outputs, best_output, ...
    options.targetScore, options.visualGateApproved);
local_register_outputs(project_root, summary_dir, best_output, gate_passed && ...
    options.visualGateApproved);

out = struct();
out.summary_dir = summary_dir;
out.metrics_csv = metrics_path;
out.upper_diagnostics_csv = diagnostics_path;
out.variants_csv = variant_path;
out.readme = readme_path;
out.best = best_output;
out.best_score = best_output.score;
out.metric_gate_passed = gate_passed;
out.visual_gate_approved = options.visualGateApproved;
out.fit_outputs = fit_outputs;

fprintf('\nB1 upper stability complete.\n');
fprintf('  Summary: %s\n', summary_dir);
fprintf('  Best: %s (%s), score %.3g, metric gate %d, visual gate %d\n', ...
    best_output.id, best_output.final_tag, best_output.score, ...
    gate_passed, options.visualGateApproved);
end


