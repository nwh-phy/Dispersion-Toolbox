function diag_rows = local_upper_diagnostics(variant, session_key, upper)
if isempty(upper) || height(upper) == 0
    diag_rows = table();
    return
end
[~, order] = sort(double(upper.q_Ainv));
upper = upper(order, :);
n = height(upper);
delta = [NaN; abs(diff(double(upper.energy_meV)))];
threshold = b1_double_peak_upper_stability_metrics(upper, session_key). ...
    upper_medium_jump_threshold_meV(1);
gamma_over_E = double(upper.gamma_meV) ./ max(abs(double(upper.energy_meV)), eps);
is_medium_jump = delta > threshold;
is_large_jump = delta > 180;
is_overbroad = gamma_over_E > 1.4 | double(upper.gamma_meV) > 1600;
source_mode = local_text_column(upper, 'source_mode');
source_q_Ainv = local_text_column(upper, 'source_q_Ainv');
repair_source = local_text_column(upper, 'repair_source');
repair_detail = local_text_column(upper, 'repair_detail');
diag_rows = table(repmat({variant.id}, n, 1), ...
    repmat({variant.final_tag}, n, 1), ...
    repmat(variant.candidate_for_recommendation, n, 1), ...
    repmat(variant.b1_energy_window(1), n, 1), ...
    repmat(variant.b1_energy_window(2), n, 1), ...
    repmat({session_key}, n, 1), ...
    upper.q_Ainv, upper.q_abs_Ainv, upper.energy_meV, delta, ...
    upper.gamma_meV, gamma_over_E, upper.R2, is_medium_jump, ...
    is_large_jump, is_overbroad, source_mode, ...
    upper.source_q_count, source_q_Ainv, repair_source, ...
    repair_detail, ...
    'VariableNames', {'variant_id', 'date_tag', ...
    'candidate_for_recommendation', 'b1_energy_min_meV', ...
    'b1_energy_max_meV', 'session_key', 'q_Ainv', 'q_abs_Ainv', ...
    'energy_meV', ...
    'delta_from_previous_meV', 'gamma_meV', 'gamma_over_E', 'R2', ...
    'is_upper_medium_jump', 'is_upper_large_jump_180', ...
    'is_overbroad_upper_peak', 'source_mode', 'source_q_count', ...
    'source_q_Ainv', 'repair_source', 'repair_detail'});
end


function score = local_variant_score(metrics, variant_id)
rows = strcmp(metrics.variant_id, variant_id);
if ~any(rows)
    score = Inf;
else
    score = sum(metrics.weighted_score(rows), 'omitnan');
end
end


function gate = local_gate_status(metrics, variant_id, target_score)
rows = strcmp(metrics.variant_id, variant_id);
if ismember('candidate_for_recommendation', metrics.Properties.VariableNames) && ...
        any(rows) && ~any(metrics.candidate_for_recommendation(rows))
    rows(:) = false;
end
upper_rows = rows & strcmp(metrics.branch, 'upper');
score = local_variant_score(metrics, variant_id);
gate = struct('total_score_ok', score <= target_score, ...
    'upper_medium_ok', false, 'upper_large_ok', false, ...
    'metric_gate_passed', false);
if ~any(upper_rows)
    return
end
upper = metrics(upper_rows, :);
is20w = strcmp(upper.session_key, 'no_PL2_20w_2film');
other = ~is20w;
gate.upper_medium_ok = any(is20w & upper.upper_medium_jump_count <= 3) && ...
    all(upper.upper_medium_jump_count(other) <= 2);
gate.upper_large_ok = all(upper.upper_large_jump_count == 0);
gate.metric_gate_passed = gate.total_score_ok && ...
    gate.upper_medium_ok && gate.upper_large_ok;
end


function best = local_choose_best_output(outputs)
if isempty(outputs)
    best = struct('id', '', 'final_tag', '', 'score', Inf, ...
        'candidate_for_recommendation', false, ...
        'b1_energy_min_meV', NaN, 'b1_energy_max_meV', NaN, ...
        'metric_gate_passed', false, 'overlay_png', "", 'overlay_pdf', "");
    return
end
recommendable = [outputs.candidate_for_recommendation];
gate = [outputs.metric_gate_passed] & recommendable;
if any(gate)
    candidates = find(gate);
else
    candidates = find(recommendable);
    if isempty(candidates)
        candidates = 1:numel(outputs);
    end
end
selection = [outputs(candidates).score] + ...
    [outputs(candidates).upper_stability_score];
[~, idx] = min(selection);
best = outputs(candidates(idx));
end


