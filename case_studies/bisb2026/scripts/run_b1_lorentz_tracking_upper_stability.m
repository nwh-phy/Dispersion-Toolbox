function local_run_variant(project_root, summary_dir, variant)
sessions = {'590', 'n0', '20w'};
for si = 1:numel(sessions)
    session_request = sessions{si};
    lower_ref = table();
    upper_ref = table();
    if strlength(string(variant.reference_tag)) > 0
        ref_dir = local_session_dir(project_root, session_request, ...
            variant.reference_tag);
        lower_ref = readtable(fullfile(ref_dir, ...
            'b1_double_peak_lower_points.csv'));
        upper_ref_raw = readtable(fullfile(ref_dir, ...
            'b1_double_peak_upper_points.csv'));
        upper_ref = local_robust_upper_reference(upper_ref_raw);
        ref_csv = fullfile(summary_dir, sprintf( ...
            '%s_%s_upper_robust_trend_reference.csv', ...
            variant.id, session_request));
        writetable(upper_ref, ref_csv);
    end
    local_call_extraction(session_request, variant, lower_ref, upper_ref);
end
end


