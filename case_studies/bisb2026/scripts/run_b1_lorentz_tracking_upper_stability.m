            isfile(variant_outputs(i).overlay_png)
        copyfile(variant_outputs(i).overlay_png, fullfile(summary_dir, ...
            sprintf(['b1_double_peak_lorentz_tracking_upper_', ...
            'stability_%s_overlay_three_dataset_comparison.png'], safe_id)));
    end
    if strlength(variant_outputs(i).overlay_pdf) > 0 && ...
            isfile(variant_outputs(i).overlay_pdf)
        copyfile(variant_outputs(i).overlay_pdf, fullfile(summary_dir, ...
            sprintf(['b1_double_peak_lorentz_tracking_upper_', ...
            'stability_%s_overlay_three_dataset_comparison.pdf'], safe_id)));
    end
end
end


function output = local_variant_output(variant, score, gate, overlay)
