    referenceUpperPoints=upper_ref, ...
    waterfallStartMeV=250, ...
    waterfallEndMeV=1600, ...
    waterfallNormMode='area', ...
    waterfallAreaNormWindowMeV=[50 3800], ...
    waterfallResidual=true, ...
    waterfallGain=2, ...
    fitDenoiseMethod='sgolay', ...
    fitDenoiseProfile='adaptive_absq', ...
    fitDenoiseLowWindow=11, ...
    fitDenoiseHighWindow=91, ...
    fitDenoiseQStartAinv=0.07, ...
    fitDenoiseQEndAinv=0.15, ...
    fitDenoiseOrder=3, ...
    highQForceBinAbsAinv=0.075, ...
    binSize=9, ...
    enableJumpRepair=true, ...
    largeJumpThresholdMeV=variant.large_jump_threshold_meV);
end


function ref = local_robust_upper_reference(points)
if isempty(points) || height(points) == 0
    ref = table();
    return
end
q = double(points.q_Ainv(:));
energy = double(points.energy_meV(:));
valid = isfinite(q) & isfinite(energy);
q = q(valid);
energy = energy(valid);
[q, order] = sort(q);
energy = energy(order);
[q_unique, ~, group] = unique(q);
energy_unique = splitapply(@median, energy, group);
if numel(energy_unique) >= 5
    energy_unique = smoothdata(energy_unique, 'movmedian', 3);
    span = min(7, numel(energy_unique));
    if mod(span, 2) == 0
        span = span - 1;
    end
    if span >= 3
        energy_unique = smoothdata(energy_unique, 'rlowess', span);
    end
elseif numel(energy_unique) >= 3
    energy_unique = smoothdata(energy_unique, 'movmedian', 3);
end
ref = table(q_unique(:), energy_unique(:), ...
    'VariableNames', {'q_Ainv', 'energy_meV'});
end


function [metrics, upper_diag] = local_finalize_variant(project_root, ...
    summary_dir, variant)
metrics = local_empty_metrics_table();
upper_diag = table();
sessions = {'590', 'n0', '20w'};
for si = 1:numel(sessions)
    session_dir = local_session_dir(project_root, sessions{si}, ...
        variant.final_tag);
    local_copy_variant_named_csv(session_dir, variant.id);
    [rows, diag_rows] = local_metrics_one_session(session_dir, variant);
    writetable(rows, fullfile(session_dir, sprintf( ...
        'b1_double_peak_lorentz_tracking_upper_stability_%s_tracking_metrics.csv', ...
        variant.id)));
    writetable(diag_rows, fullfile(session_dir, sprintf( ...
        'b1_double_peak_lorentz_tracking_upper_stability_%s_upper_jump_gamma_R2.csv', ...
        variant.id)));
    metrics = [metrics; rows]; %#ok<AGROW>
    upper_diag = [upper_diag; diag_rows]; %#ok<AGROW>
end
if ~isempty(upper_diag)
    writetable(upper_diag, fullfile(summary_dir, sprintf( ...
        'b1_double_peak_lorentz_tracking_upper_stability_%s_upper_jump_gamma_R2.csv', ...
        variant.id)));
end
end


