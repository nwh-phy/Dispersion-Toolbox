function out = bisb_datasets(id)
%BISB_DATASETS  The one registry of the q-EELS acquisitions of the 2D-metal project.
%   D = bisb_datasets() returns every entry as a struct array.
%   d = bisb_datasets(id) returns one entry; id may be the canonical id, the
%   short name or any alias (case-insensitive). Unknown ids raise an error that
%   lists the known ones.
%
%   A new acquisition is added here once (folder, dq, q = 0 channel, hash);
%   analysis code takes the id and reads the rest from this table instead of
%   hard-coding folders or calibrations in each script.
%
%   Fields
%     id          canonical id (session names of the thesis / adaptive-q / P2 code)
%     short       short id (b1_low_branch_matlab sessions)
%     aliases     further accepted names
%     sample      sample, and layers = number of metal layers
%     acquired    acquisition start, local time
%     defocus_um  sample-height defocus; n_frames x frame_s exposure
%     set         data folder at the project root
%     folder      acquisition subfolder inside set
%     file        raw sequence (.npy; the .json sits next to it)
%     path        absolute path of file
%     dq          momentum step, 1/A per native channel
%     dq_status   where dq comes from
%     zero        native channel (1-based) of q = 0
%     h           slot acceptance across the dispersion axis (1/A); NaN = not known
%     sha256      SHA-256 of the raw .npy (b1_sha256 / shasum -a 256)
%     notes
%
%   See also: bisb_find_project_root, b1_low_branch_matlab_config

root = bisb_find_project_root(fileparts(mfilename('fullpath')));
D = [ ...
    entry('590_PL2_10w', '590', {}, 'C20 BiSb (Bi 70 / Sb 30 at.%)', 1, '2026-01-21 02:20', 100, 300, 10, ...
          '20260120 BiSb', '590 PL2 10w 0.004 10sx300', 'Sequence EELS Image 274.npy', ...
          0.0005, 'calibrated (2026-05-14 correction)', 236, 0.0066, ...
          '14b832170e0d52c742612a8045e436cdc735aefb5aefb9ea458bab04280765a9', ...
          'main BiSb dataset; native channel 461 is a bad channel'), ...
    entry('n0_PL2_10w_repeat', 'n0', {}, 'C20 BiSb (Bi 70 / Sb 30 at.%)', 1, '2026-01-20 23:07', 100, 300, 10, ...
          '20260120 BiSb', 'n0 pl2 10w 0.004 10s x300', 'Sequence EELS Image 272.npy', ...
          0.0005, 'calibrated (2026-05-14 correction)', 235, 0.0066, ...
          'ec11302d24a91658feaf11180e52a83c0e011fdc0271bc42db9b2dbde07544f4', ...
          'second 1L region, 0.85 um from 590; native channel 461 is a bad channel'), ...
    entry('no_PL2_20w_2film', '20w', {}, 'C20 BiSb (Bi 70 / Sb 30 at.%)', 2, '2026-01-21 00:51', 200, 300, 10, ...
          '20260120 BiSb', 'no pl2 20w 0.004 10sx300 2film', 'Sequence EELS Image 273.npy', ...
          0.00025, 'calibrated (2026-05-14 correction)', 236, 0.0033, ...
          'fb78863f0bc70878801fcee8f113d93e882c428513efb4a84c27a14929c5f9f6', ...
          '2L region 8.8 um from 590; h = 0.0033 is an estimate'), ...
    entry('Bi1107_10w', 'Bi10w', {'20261107_Bi_10w'}, 'Bi 1L (MoS2/Bi/MoS2)', 1, '2026-11-07 14:57', 100, 360, 10, ...
          '20261107 Bi', '0.004 +10w 10sx360', 'Sequence EELS Image 170.npy', ...
          0.0005, 'provisional: 20260120 10w calibration, camera E-01-0533 not re-calibrated', 229, NaN, ...
          '6ddd26f097f1212fe5fd0cf8499de472bab25098313e4af4be69121c33973e2d', ...
          'Huairou Nion; zero = elastic maximum of the frame sum; Ronchigram files in the same folder'), ...
    entry('Bi1107_20w', 'Bi20w', {'20261107_Bi_20w'}, 'Bi 1L (MoS2/Bi/MoS2)', 1, '2026-11-07 16:26', 200, 180, 10, ...
          '20261107 Bi', '0.004 +20w 10sx180', 'Sequence EELS Image 173.npy', ...
          0.00025, 'provisional: 20260120 20w calibration, camera E-01-0533 not re-calibrated', 228, NaN, ...
          'e09f56cc0ae768f2395c4aa90f7236707f04e69215a3f7843cf939ece852e1d4', ...
          'Huairou Nion; zero = elastic maximum of the frame sum')];
for k = 1:numel(D)
    D(k).path = fullfile(root, D(k).set, D(k).folder, D(k).file);
end
if nargin < 1
    out = D;
    return
end
id = char(id);
hit = false(1, numel(D));
for k = 1:numel(D)
    hit(k) = any(strcmpi(id, [{D(k).id, D(k).short}, D(k).aliases]));
end
if ~any(hit)
    error('bisb_datasets:Unknown', 'Unknown dataset "%s". Known: %s', id, strjoin({D.id}, ', '));
end
out = D(hit);
end

function d = entry(id, short, aliases, sample, layers, acquired, defocus_um, n_frames, frame_s, ...
    set, folder, file, dq, dq_status, zero, h, sha256, notes)
d = struct('id', id, 'short', short, 'aliases', {aliases}, 'sample', sample, 'layers', layers, ...
    'acquired', acquired, 'defocus_um', defocus_um, 'n_frames', n_frames, 'frame_s', frame_s, ...
    'set', set, 'folder', folder, 'file', file, 'path', '', 'dq', dq, 'dq_status', dq_status, ...
    'zero', zero, 'h', h, 'sha256', sha256, 'notes', notes);
end
