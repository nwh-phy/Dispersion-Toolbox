function cfg = b1_p2b_config()
% Override of the main-checkout b1_p2b_config for the h scan of P2b (b1_p2b_hscan_run puts
% this folder first on the path and sets B1_P2B_H). Identical except:
%   version  carries h (one output folder per h)
%   nodes    E0 at 0.0005 0.001 0.002 0.004 0.008, width and residue at 0.0005 0.002 0.008:
%            with a wide slot the channels collect Q up to sqrt(0.005^2 + h^2) ~ 0.008, so
%            the top node moves from 0.005 to 0.008 (b1_p2b_fit fixes the node counts)
%   variants main and y: Gaussian
h = str2double(getenv('B1_P2B_H'));
assert(isfinite(h) && h > 0, 'b1_p2b_config:h', 'set B1_P2B_H (A^-1) before calling');
cfg.version = sprintf('P2b-2026-10-15b+hscan-h%.4f-top0.008', h);
cfg.exit_q = [-0.005:0.0005:-0.0005, 0.0005:0.0005:0.005];   % 20 native channels
cfg.holdout = [150 250];
cfg.nodes = struct('E0', [0.0005 0.001 0.002 0.004 0.008], 'G', [0.0005 0.002 0.008], 'A', [0.0005 0.002 0.008]);
cfg.tail = struct('p', 4, 'E_ref', 250);    % per-spectrum power-law tail (projected out), absorbs aux / instrument tails at the low edge
cfg.noise_smooth = 21;                      % sigma^2 = 21-point moving mean of the counts (Neyman weights bias E0: P2a step 2.4)
cfg.lambda_curv = 10;                       % weak curvature penalty on log E0^2 over the nodes
cfg.bounds_E0 = [150 1300; 800 2500];       % meV, low / high branch
cfg.bounds_G = [30 3000];                   % meV
cfg.starts = struct( ...
    'name', {'P1b reference', 'flat', 'low-Q drop', 'high-q averages'}, ...
    'E0', {[800 775 740 718 713; 1550 1610 1700 1650 1594], [760 760 760 760 760; 1650 1650 1650 1650 1650], ...
           [450 600 720 730 720; 1200 1400 1600 1650 1600], [800 780 740 705 712; 1600 1640 1720 1640 1585]}, ...
    'G', {[380 560 580; 750 1700 1775], [380 560 580; 750 1700 1775], [380 560 580; 750 1700 1775], [400 560 600; 800 1800 1720]});
cfg.variants = struct( ...
    'name', {'main', 'y: Gaussian'}, ...
    'kernel', {'slice', 'slice'}, ...
    'wide', {'on', 'on'}, ...
    'ext', {'const', 'const'}, ...
    'ytype', {'mixture', 'gauss'}, ...
    'window', {[250 1800], [250 1800]}, ...
    'tail', {true, true}, ...
    'lowq_emax', {Inf, Inf});
cfg.lobo_block = 6;                         % left out of the main fit and predicted
cfg.Q_curve = exp(linspace(log(0.0005), log(0.008), 49));
cfg.highq = struct('file', fullfile('stage5', 'e0_stage2_2d_h5_590_PL2_10w.csv'), 'q_range', [0.0055 0.0155], 'err_floor', 10);
end
